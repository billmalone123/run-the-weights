"""8.39 running without a race: setup (Do you run, days a week, race Skip), the Run tab with no race, the Today tile,
Settings Running, existing users, backup with monk_run_base_v1, and a race set later. 390 and 320."""
import sys, os, json, tempfile; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *
from playwright.sync_api import sync_playwright
FRESH = "localStorage.setItem('monk_onboarded_v1','1');" + SEEN
CLOSE = "document.querySelectorAll('.settings-modal-overlay').forEach(m=>m.style.display='none')"
BASE = "JSON.parse(localStorage.getItem('monk_run_base_v1'))"
LOGS = "localStorage.getItem('monk_run_logs_v1')"
# Two runs this week (Mon 16, Tue 17), one last week. The clock sits on Thu 19 Nov 2026.
RUNS = {'2026-11-16': {'miles': 3, 'secs': 1620, 'type': 'easy'}, '2026-11-17': {'miles': 4.2, 'secs': 2300, 'type': 'easy'}, '2026-11-10': {'miles': 5, 'secs': 2700, 'type': 'long'}}
def user(b, W=390, runs=None, base=None, race=None, on=True, km=False):
    init = INIT + "localStorage.setItem('monk_running_v1','%s');" % ('1' if on else '0')
    if runs is not None: init += "localStorage.setItem('monk_run_logs_v1',%s);" % json.dumps(json.dumps(runs))
    if base is not None: init += "localStorage.setItem('monk_run_base_v1',%s);" % json.dumps(json.dumps(base))
    if race: init += "localStorage.setItem('monk_run_plan_v1',%s);" % json.dumps(json.dumps({'raceDate': race, 'distance': 'half', 'level': 'casual', 'current': 15, 'peak': 30}))
    if km: init += "localStorage.setItem('monk_run_units_v1','km');"
    init += "if(!sessionStorage.getItem('x')){sessionStorage.setItem('x','1');" + ("" if runs is not None else "localStorage.removeItem('monk_run_logs_v1');") + "}"
    ctx = b.new_context(viewport={'width': W, 'height': 844}, service_workers='block'); pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=T0); pg.add_init_script(init); pg.goto(URL); pg.wait_for_timeout(1500); pg.evaluate(CLOSE)
    return ctx, pg, errs
def wizard(b, W):
    ctx = b.new_context(viewport={'width': W, 'height': 844}, service_workers='block'); pg = ctx.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.clock.install(time=T0); pg.add_init_script(FRESH); pg.goto(URL); pg.wait_for_timeout(1200)
    pg.evaluate("onb={};onbSaveDraft();openOnboardingWizard();onbPick('days',4);onbNext();['squat','bench','ohp'].forEach(k=>onbSetMaxMode(k,'skip'));onbNext()"); pg.wait_for_timeout(300)
    return ctx, pg, errs
def tile(pg): go(pg, 'today'); return pg.evaluate("(document.querySelector('#tbStats .tb-run')||{}).innerText||''").lower()
def runsum(pg): go(pg, 'running'); return pg.evaluate("runBaseSum.hidden?'':runBaseSum.innerText")
with sync_playwright() as p:
    b = p.chromium.launch()
    # ---------- setup ----------
    for W in [390, 320]:
        ctx, pg, errs = wizard(b, W)
        check('%d: the runs step is open' % W, pg.evaluate("onb.step") == 'runs', pg.evaluate("onb.step"))
        ch = pg.evaluate("[...document.querySelectorAll('#onbBody .onb-choice')].map(e=>e.textContent)")
        check('%d: Do you run offers the three answers' % W, ch == ['Yes, regularly', 'A little', 'Not now'], ch)
        pg.click('#onbBody .onb-choice:has-text("A little")'); pg.wait_for_timeout(200)
        days = pg.evaluate("[...document.querySelectorAll('#onbBody .onb-rundays .liftdays-btn')].map(e=>e.textContent+':'+e.getAttribute('aria-pressed'))")
        check('%d: A little asks days a week, 1 to 5, 3 chosen' % W, days == ['1:false', '2:false', '3:true', '4:false', '5:false'], days)
        small = pg.evaluate("[...document.querySelectorAll('#onbBody button')].map(e=>{var r=e.getBoundingClientRect();return [e.textContent,Math.round(r.width),Math.round(r.height)]}).filter(x=>x[1]<44||x[2]<44)")
        check('%d: every setup button is 44 px or larger' % W, not small, small)
        check('%d: no sideways scroll' % W, pg.evaluate("document.documentElement.scrollWidth<=innerWidth"))
        fit = pg.evaluate("(()=>{var c=document.getElementById('onbWizardCard').getBoundingClientRect();return [...document.querySelectorAll('#onbBody button')].every(e=>{var r=e.getBoundingClientRect();return r.left>=c.left-1&&r.right<=c.right+1})})()")
        check('%d: every setup button sits inside the card' % W, fit)
        pg.click('#onbBody .onb-rundays .liftdays-btn:has-text("2")'); pg.wait_for_timeout(150)
        pg.screenshot(path=shot('839-setup-%d.png' % W))
        pg.evaluate("onbNext();onbPick('mileage','0-10');onbNext()"); pg.wait_for_timeout(200)
        rc = pg.evaluate("[...document.querySelectorAll('#onbBody .onb-choice')].map(e=>e.textContent+':'+e.classList.contains('on'))")
        check('%d: the race question has Skip first and chosen' % W, rc == ['Skip:true', 'Yes, add a race date:false'] and pg.evaluate("!onbNextBtn.disabled"), rc)
        pg.evaluate("onbNext()"); pg.wait_for_timeout(200)
        check('%d: the summary says 2 runs a week and no race' % W, '2 runs a week' in pg.evaluate("onbBody.innerText") and 'No race.' in pg.evaluate("onbBody.innerText"))
        pg.evaluate("onbNext()"); pg.wait_for_timeout(600)
        check('%d: the answers save: on, 2 a week' % W, pg.evaluate(BASE) == {'on': True, 'perWeek': 2, 'weeklyTarget': None} and pg.evaluate("runningEnabled"), pg.evaluate(BASE))
        check('%d: Skip stores no race' % W, not pg.evaluate("runPlan.raceDate"))
        check('%d: setup: no page errors' % W, not errs, errs); ctx.close()
    ctx, pg, errs = wizard(b, 390)
    pg.click('#onbBody .onb-choice:has-text("Not now")'); pg.wait_for_timeout(200)
    check('Not now goes straight on and says running stays one tap away', pg.evaluate("onbSteps().join()") == 'days,maxes,runs,done' and 'one tap away' in pg.evaluate("onbBody.innerText"))
    pg.evaluate("onbNext();onbNext()"); pg.wait_for_timeout(600)
    check('Not now saves running off', pg.evaluate(BASE)['on'] is False and not pg.evaluate("runningEnabled"))
    go(pg, 'running')
    check('Not now hides nothing for good: Run still offers Turn on running', pg.evaluate("getComputedStyle(runOff).display!=='none'") and 'Turn on running' in pg.evaluate("runOff.innerText"))
    pg.click('#runOff .today-start'); pg.wait_for_timeout(400)
    check('and turning it on brings the Run home back', pg.evaluate("runningEnabled") and pg.evaluate(BASE)['on'] is True)
    ctx.close()
    ctx, pg, errs = wizard(b, 390)
    pg.click('#onbBody .onb-choice:has-text("Yes, regularly")'); pg.evaluate("onbNext();onbPick('mileage','10-20');onbNext();onbPick('race',true)"); pg.wait_for_timeout(200)
    check('Yes on the race question runs the race date flow', pg.evaluate("!!document.getElementById('onb-race-date')") and 'distance' in pg.evaluate("onbSteps().join()"))
    ctx.close()
    # ---------- Run tab and Today with no race ----------
    for W in [390, 320]:
        ctx, pg, errs = user(b, W, runs=RUNS, base={'on': True, 'perWeek': 3, 'weeklyTarget': 15})
        rs = runsum(pg)
        check('%d: Run shows 2 of 3 and this week distance' % W, 'RUNS THIS WEEK' in rs.upper() and '2 of 3' in rs and '7.2 mi this week' in rs, rs)
        check('%d: the weekly target is a progress line' % W, '7.2 mi of 15 mi target' in rs and pg.evaluate("document.querySelector('#runBaseSum [role=progressbar]').getAttribute('aria-valuetext')") == '7.2 mi of 15 mi', rs)
        check('%d: Log a run is the main button' % W, pg.evaluate("document.querySelector('#runTodayCard .today-start').textContent") == 'Log a run')
        check('%d: recent runs come from the logs' % W, pg.evaluate("document.querySelectorAll('#runTable tbody tr').length") == 3)
        lk = pg.evaluate("(()=>{var e=runPlanBtn,r=e.getBoundingClientRect();return [e.textContent,Math.round(r.height)]})()")
        check('%d: a quiet Add a race for a plan link' % W, lk[0] == 'Add a race for a plan' and lk[1] >= 44, lk)
        body = pg.evaluate("document.getElementById('runHome').innerText")
        check('%d: no schedule or plan on the Run home' % W, not any(x in body.lower() for x in ['planned', 'tempo', 'target pace', 'week 1 of']), body[:300])
        check('%d: no sideways scroll on Run' % W, pg.evaluate("document.documentElement.scrollWidth<=innerWidth"))
        pg.screenshot(path=shot('839-run-norace-%d.png' % W))
        t = tile(pg)
        check('%d: Today shows Runs this week 2 of 3 with Log a run' % W, '2 of 3' in t and 'log a run' in t, t)
        bt = pg.evaluate("(()=>{var r=document.querySelector('.tb-run-log').getBoundingClientRect();return Math.round(r.height)})()")
        check('%d: the tile button is 44 px' % W, bt >= 44, bt)
        pg.evaluate("document.getElementById('tbStats').scrollIntoView({block:'center'})"); pg.wait_for_timeout(150)
        pg.screenshot(path=shot('839-today-tile-%d.png' % W))
        # Log from Today.
        pg.click('.tb-run-log'); pg.wait_for_timeout(300)
        check('%d: Log a run on Today opens the run log' % W, pg.evaluate("runLogSheet.style.display") == 'flex')
        pg.fill('#rlDist', '3'); pg.fill('#rlMin', '27'); pg.click('#runLogSheet .today-start:has-text("Save")'); pg.wait_for_timeout(500)
        pg.evaluate(CLOSE)
        t = tile(pg)
        check('%d: logging a run updates Today to 3 of 3' % W, '3 of 3' in t, t)
        check('%d: and the Run tab' % W, '3 of 3' in runsum(pg))
        # Settings.
        pg.evaluate("openSettingsModal()"); pg.wait_for_timeout(300)
        pg.evaluate("document.getElementById('runBaseSet').scrollIntoView({block:'center'})"); pg.wait_for_timeout(150)
        st = pg.evaluate("runBaseSet.innerText")
        check('%d: Settings Running has days a week, a target and the race' % W, 'Runs a week' in st and 'Weekly distance target, mi, optional' in st and 'No race set.' in st, st)
        small = pg.evaluate("[...document.querySelectorAll('#runBaseSet button, #runBaseSet input')].map(e=>{var r=e.getBoundingClientRect();return [e.textContent||e.id,Math.round(r.width),Math.round(r.height)]}).filter(x=>x[1]<44||x[2]<44)")
        check('%d: Settings Running controls are 44 px' % W, not small, small)
        pg.screenshot(path=shot('839-settings-%d.png' % W))
        pg.click('#runBaseSet .liftdays-btn:has-text("4")'); pg.fill('#rbTarget', '20'); pg.dispatch_event('#rbTarget', 'change'); pg.wait_for_timeout(200)
        check('%d: Settings changes save' % W, pg.evaluate(BASE) == {'on': True, 'perWeek': 4, 'weeklyTarget': 20})
        pg.evaluate(CLOSE)
        check('%d: and show on Today' % W, '3 of 4' in tile(pg))
        check('%d: no page errors' % W, not errs, errs); ctx.close()
    # km
    ctx, pg, errs = user(b, 390, runs=RUNS, base={'on': True, 'perWeek': 3, 'weeklyTarget': 15}, km=True)
    rs = runsum(pg)
    check('km: distance and target in km', '11.6 km this week' in rs and 'of 24.1 km target' in rs, rs)
    pg.evaluate("openSettingsModal()"); pg.fill('#rbTarget', '30'); pg.dispatch_event('#rbTarget', 'change'); pg.wait_for_timeout(200)
    check('km: a target typed in km is stored in miles', abs(pg.evaluate(BASE)['weeklyTarget'] - 18.64) < 0.01, pg.evaluate(BASE))
    ctx.close()
    # ---------- existing users ----------
    ctx, pg, errs = user(b, runs=RUNS, race='2027-03-07')
    check('with a race: the Run home is unchanged', runsum(pg) == '' and pg.evaluate("runPlanBtn.textContent") == 'Race plan and full schedule')
    check('with a race: no runs this week tile', tile(pg) == '')
    ctx.close()
    ctx, pg, errs = user(b, runs=RUNS)
    check('runs and no race and no answer: a runner with a goal of 3', '2 of 3' in runsum(pg) and '2 of 3' in tile(pg) and pg.evaluate("localStorage.getItem('monk_run_base_v1')") is None)
    ctx.close()
    ctx, pg, errs = user(b)
    rs = runsum(pg)
    check('no runs, no race, no answer: a plain empty state', 'No runs yet' in rs and 'of 3' not in rs and pg.evaluate("document.querySelector('#runTodayCard .today-start').textContent") == 'Log a run', rs)
    check('and no Today tile', tile(pg) == '')
    ctx.close()
    ctx, pg, errs = user(b, runs=RUNS, on=False)
    check('running off: no Today tile', tile(pg) == '')
    ctx.close()
    # ---------- a race later, backup ----------
    ctx, pg, errs = user(b, runs=RUNS, base={'on': True, 'perWeek': 3, 'weeklyTarget': None})
    before = pg.evaluate(LOGS)
    go(pg, 'running'); pg.click('#runPlanBtn'); pg.wait_for_timeout(400)
    check('Add a race for a plan opens the race date field', pg.evaluate("document.activeElement.id") == 'run-race-date')
    pg.fill('#run-race-date', '2027-03-07'); pg.dispatch_event('#run-race-date', 'change'); pg.wait_for_timeout(500)
    check('setting a race hands over to the race plan', pg.evaluate("raceActive()") and runsum(pg) == '' and pg.evaluate("runPlanBtn.textContent") == 'Race plan and full schedule')
    check('no logged run is lost or changed', json.loads(pg.evaluate(LOGS)) == json.loads(before))
    with pg.expect_download() as dl: pg.evaluate("exportData()")
    data = json.load(open(dl.value.path()))
    check('the backup carries run base', data.get('runBase') == {'on': True, 'perWeek': 3, 'weeklyTarget': None}, data.get('runBase'))
    data['runBase'] = {'on': True, 'perWeek': 5, 'weeklyTarget': 12}
    fd, path = tempfile.mkstemp(suffix='.json'); os.write(fd, json.dumps(data).encode()); os.close(fd)
    pg.evaluate(CLOSE + ";openSettingsModal()"); pg.set_input_files('#settingsModal input[type=file]', path); pg.wait_for_timeout(1200)
    check('restoring brings run base back', pg.evaluate(BASE) == {'on': True, 'perWeek': 5, 'weeklyTarget': 12})
    old = dict(data); old.pop('runBase')
    fd, path2 = tempfile.mkstemp(suffix='.json'); os.write(fd, json.dumps(old).encode()); os.close(fd)
    pg.evaluate(CLOSE + ";openSettingsModal()"); pg.set_input_files('#settingsModal input[type=file]', path2); pg.wait_for_timeout(1200)
    check('an old backup without it loads, and its runs are unchanged', pg.evaluate("localStorage.getItem('monk_run_base_v1')") is None and json.loads(pg.evaluate(LOGS)) == json.loads(before))
    bad = dict(data); bad['runBase'] = {'on': 'yes', 'perWeek': 99, 'weeklyTarget': '<b>'}
    fd, path3 = tempfile.mkstemp(suffix='.json'); os.write(fd, json.dumps(bad).encode()); os.close(fd)
    pg.evaluate(CLOSE + ";openSettingsModal()"); pg.set_input_files('#settingsModal input[type=file]', path3); pg.wait_for_timeout(1200)
    check('a bad run base in a backup is cleaned', pg.evaluate(BASE) == {'on': False, 'perWeek': 3, 'weeklyTarget': None}, pg.evaluate(BASE))
    check('race and backup: no page errors', not errs, errs); ctx.close()
    b.close()
sys.exit(1 if done() else 0)
